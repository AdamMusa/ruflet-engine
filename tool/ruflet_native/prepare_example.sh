#!/usr/bin/env bash
# Generates the host folders (android/, ios/, web/) of a ruflet_native dev app
# and applies the per-feature patches found in its patches/ folder.
#
#   tool/ruflet_native/prepare_example.sh [example|fixture_recorder] [--swiftpm|--cocoapods] [--web]
#
# The host folders are never committed: a committed MainActivity.kt or
# AppDelegate.swift would be a native source file, which ruflet_native
# forbids (check_no_native_sources.sh). `flutter create` writes the stock
# Flutter ones, which contain no Ruflet code.
#
# Patches (discovered by glob, so feature PRs only add files):
#   patches/<feature>.plist          keys merged into ios/Runner/Info.plist
#   patches/<feature>.manifest.xml   lines inserted into the <manifest> of
#                                    android/app/src/main/AndroidManifest.xml
#   patches/<feature>.gradle.properties  lines appended to android/gradle.properties
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
app="example"
spm=""
web=0
for arg in "$@"; do
  case "$arg" in
    example|fixture_recorder) app="$arg" ;;
    --swiftpm) spm="true" ;;
    --cocoapods) spm="false" ;;
    --web) web=1 ;;
    *) echo "unknown argument: $arg" >&2; exit 2 ;;
  esac
done

dir="$here/$app"
cd "$dir"

# The recorder's pubspec.yaml is generated: pubspec.base.yaml plus every
# deps/<feature>.yaml (the old package of each recorded feature).
if [ -f pubspec.base.yaml ]; then
  python3 - <<'PY'
import glob
base = open('pubspec.base.yaml').read()
marker = '  # ruflet_native_recorder_deps\n'
deps = ''.join(open(p).read() for p in sorted(glob.glob('deps/*.yaml')))
open('pubspec.yaml', 'w').write(
    '# Generated by tool/ruflet_native/prepare_example.sh from pubspec.base.yaml.\n'
    + base.replace(marker, marker + deps))
PY
fi

# The example replays the recorded fixtures: copy them in as assets.
if [ "$app" = example ]; then
  rm -rf fixtures && mkdir -p fixtures
  for f in "$here"/../../packages/ruflet/native/test/fixtures/*/*.json; do
    [ -f "$f" ] || continue
    feature="$(basename "$(dirname "$f")")"
    cp "$f" "fixtures/$feature.$(basename "$f")"
  done
  touch fixtures/.keep
fi

name="$(sed -n 's/^name: *//p' pubspec.yaml | head -n1)"
platforms="android,ios"
if [ "$web" = 1 ]; then platforms="$platforms,web"; fi

flutter create --no-pub --platforms="$platforms" --org dev.ruflet --project-name "$name" . >/dev/null

# flutter create adds a counter-app widget test when test/ has none.
if [ -f test/widget_test.dart ] && grep -q 'MyApp' test/widget_test.dart; then
  rm test/widget_test.dart
  rmdir test 2>/dev/null || true
fi

# iOS like the Ruflet template: deployment target 16.0 and static
# frameworks (`use_frameworks! :linkage => :static`). Xcode 27 rejects
# deployment targets below 15.0, so pods that declare less are raised too.
sed -i.bak 's/IPHONEOS_DEPLOYMENT_TARGET = [0-9.]*;/IPHONEOS_DEPLOYMENT_TARGET = 16.0;/' \
  ios/Runner.xcodeproj/project.pbxproj && rm ios/Runner.xcodeproj/project.pbxproj.bak
cat > ios/Podfile <<'PODFILE'
# Generated by tool/ruflet_native/prepare_example.sh (Ruflet template settings).
platform :ios, '16.0'

ENV['COCOAPODS_DISABLE_STATS'] = 'true'

project 'Runner', {
  'Debug' => :debug,
  'Profile' => :release,
  'Release' => :release,
}

def flutter_root
  generated_xcode_build_settings_path = File.expand_path(File.join('..', 'Flutter', 'Generated.xcconfig'), __FILE__)
  unless File.exist?(generated_xcode_build_settings_path)
    raise "#{generated_xcode_build_settings_path} must exist. If you're running pod install manually, make sure flutter pub get is executed first"
  end

  File.foreach(generated_xcode_build_settings_path) do |line|
    matches = line.match(/FLUTTER_ROOT\=(.*)/)
    return matches[1].strip if matches
  end
  raise "FLUTTER_ROOT not found in #{generated_xcode_build_settings_path}. Try deleting Generated.xcconfig, then run flutter pub get"
end

require File.expand_path(File.join('packages', 'flutter_tools', 'bin', 'podhelper'), flutter_root)

flutter_ios_podfile_setup

target 'Runner' do
  use_frameworks! :linkage => :static

  flutter_install_all_ios_pods File.dirname(File.realpath(__FILE__))
  target 'RunnerTests' do
    inherit! :search_paths
  end
end

post_install do |installer|
  installer.pods_project.targets.each do |target|
    flutter_additional_ios_build_settings(target)
    target.build_configurations.each do |config|
      current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
      if current && Gem::Version.new(current) < Gem::Version.new('16.0')
        config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '16.0'
      end
    end
  end
end
PODFILE

# Swift Package Manager or CocoaPods for this app only (no global flutter
# config change): Flutter reads `flutter: config:` from the app's pubspec.
if [ -n "$spm" ]; then
  python3 - "$spm" <<'PY'
import re, sys
value = sys.argv[1]
text = open('pubspec.yaml').read()
text = re.sub(r'\n  config:\n    enable-swift-package-manager: \w+\n', '\n', text)
text = text.replace('\nflutter:\n', '\nflutter:\n  config:\n    enable-swift-package-manager: %s\n' % value, 1)
open('pubspec.yaml', 'w').write(text)
PY
fi

shopt -s nullglob
plists=(patches/*.plist)
manifests=(patches/*.manifest.xml)
props=(patches/*.gradle.properties)

if [ ${#plists[@]} -gt 0 ]; then
  python3 - ios/Runner/Info.plist ${plists[@]+"${plists[@]}"} <<'PY'
import plistlib, sys
target = sys.argv[1]
with open(target, 'rb') as f:
    info = plistlib.load(f)
for patch in sys.argv[2:]:
    with open(patch, 'rb') as f:
        info.update(plistlib.load(f))
with open(target, 'wb') as f:
    plistlib.dump(info, f)
PY
fi

if [ ${#manifests[@]} -gt 0 ]; then
  python3 - android/app/src/main/AndroidManifest.xml ${manifests[@]+"${manifests[@]}"} <<'PY'
import sys
target = sys.argv[1]
text = open(target).read()
marker = '<!-- ruflet_native patches -->'
if marker in text:
    text = text.split(marker)[0] + text.split(marker)[2]
lines = ''.join(open(p).read() for p in sys.argv[2:])
anchor = text.index('<application')
text = text[:anchor] + marker + '\n' + lines + marker + '\n    ' + text[anchor:]
open(target, 'w').write(text)
PY
fi

for prop in ${props[@]+"${props[@]}"}; do
  while IFS= read -r line; do
    grep -qxF -- "$line" android/gradle.properties || printf '%s\n' "$line" >> android/gradle.properties
  done < "$prop"
done

echo "prepared $app ($platforms${spm:+, swiftpm=$spm}); patches: ${plists[*]:-} ${manifests[*]:-} ${props[*]:-}"
